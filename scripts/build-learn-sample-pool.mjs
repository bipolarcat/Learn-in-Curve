/**
 * Build ring-fenced sample-question pool for /learn pages.
 * Excludes: mock_suitable, mock.json prompts, FREE_MOCK_QUESTIONS.
 * Run: node scripts/build-learn-sample-pool.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from "fs";
import { join } from "path";

const dir = join(process.cwd(), "PMQ in 5 days", "content");
const freeMockSrc = readFileSync(
  join(process.cwd(), "src/content/free-mock-exam.ts"),
  "utf8",
);
const freePrompts = new Set(
  [...freeMockSrc.matchAll(/"prompt":\s*"((?:\\.|[^"\\])*)"/g)].map((m) =>
    JSON.parse(`"${m[1]}"`).slice(0, 80),
  ),
);
const freeIds = new Set(
  [...freeMockSrc.matchAll(/"id":\s*"(LO\d+-q[^"]+)"/g)].map((m) => m[1]),
);

const mock = JSON.parse(readFileSync(join(dir, "mock.json"), "utf8"));
const mockPrompts = new Set();
for (const part of mock.parts ?? []) {
  for (const q of part.questions ?? []) {
    if (["mcq", "scenario_mcq", "dropdown"].includes(q.type)) {
      mockPrompts.add((q.question || "").slice(0, 80));
    }
  }
}

const pool = [];
for (let n = 1; n <= 24; n++) {
  const j = JSON.parse(readFileSync(join(dir, `lo${n}.json`), "utf8"));
  for (const q of j.quiz || []) {
    if (!["mcq", "scenario_mcq", "dropdown"].includes(q.type)) continue;
    if (q.mock_suitable) continue;
    const prompt = q.question || "";
    const p80 = prompt.slice(0, 80);
    if (mockPrompts.has(p80)) continue;
    if (freePrompts.has(p80)) continue;
    const id = `LO${n}-${q.id}`;
    if (freeIds.has(id)) continue;

    /** @type {Record<string, unknown>} */
    const item = {
      id,
      lo_number: n,
      lo_code: `LO${n}`,
      lo_title: j.title,
      type: q.type,
      prompt,
      marks: q.marks || 1,
      explanation: q.explanation ?? null,
    };
    if (q.type === "mcq" || q.type === "scenario_mcq") {
      item.options = q.options;
      item.correct_answer = q.correct_answer;
    } else {
      item.dropdowns = q.dropdowns;
      item.correct_answers = q.correct_answers;
    }
    pool.push(item);
  }
}

mkdirSync(join(process.cwd(), "src/content/learn"), { recursive: true });

const header = `/**
 * Auto-generated ring-fenced practice samples for /learn pages.
 * Regenerated by scripts/build-learn-sample-pool.mjs — do not hand-edit.
 * Excludes mock_suitable, mock.json prompts, and FREE_MOCK_QUESTIONS.
 */

export type LearnSampleMcq = {
  id: string;
  lo_number: number;
  lo_code: string;
  lo_title: string;
  type: "mcq" | "scenario_mcq";
  prompt: string;
  options: string[];
  correct_answer: string;
  marks: number;
  explanation: string | null;
};

export type LearnSampleDropdown = {
  id: string;
  lo_number: number;
  lo_code: string;
  lo_title: string;
  type: "dropdown";
  prompt: string;
  dropdowns: Record<string, string[]>;
  correct_answers: Record<string, string>;
  marks: number;
  explanation: string | null;
};

export type LearnSampleQuestion = LearnSampleMcq | LearnSampleDropdown;

`;

const body = `export const LEARN_SAMPLE_POOL: LearnSampleQuestion[] = ${JSON.stringify(pool, null, 2)};
`;

writeFileSync(
  join(process.cwd(), "src/content/learn/sample-pool.ts"),
  header + body,
);
console.log(`Wrote ${pool.length} eligible samples`);
